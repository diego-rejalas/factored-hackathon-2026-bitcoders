export function tr(language: Language, key: string): string {
  return messages[language][key] ?? messages.es[key] ?? key;
}

export function scenarioLabel(scenario: string, language: Language): string {
  const labels: Record<string, Record<Language, string>> = {
    auto_resolved: { es: "Auto-resuelto", pt: "Resolvido automaticamente" },
    ambiguous: { es: "Ambiguo", pt: "Ambíguo" },
    fraud: { es: "Revisión por posible fraude", pt: "Revisão por possível fraude" },
    threshold: { es: "Sobre el umbral", pt: "Acima do limite" },
  };
  return labels[scenario]?.[language] ?? scenario;
}

